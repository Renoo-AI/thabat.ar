// the card in the reader's language: Arabic is the source, en/fr live in facts.i18n.js (same order as FACTS)
function factText(f) {
  const tr = typeof FACTS_I18N !== "undefined" && LANG !== "ar" ? FACTS_I18N[LANG] : null;
  const pair = tr && tr.cards[f.i];
  return { t: pair ? pair[1] : f.t, b: pair ? pair[2] : f.b, alt: tr && tr.alt[f.k] ? tr.alt[f.k] : f.alt };
}

// today's card: exactly one per day, in a fixed order, chosen by the protected day count
function factForDay(day, reason) {
  const base = FACTS.filter((f) => !f.r), mine = FACTS.filter((f) => f.r === reason);
  const step = Math.floor(base.length / (mine.length + 1)) || base.length;
  const pool = [];
  base.forEach((f, i) => { pool.push(f); if ((i + 1) % step === 0 && mine.length) pool.push(mine.shift()); });
  pool.push(...mine); // anything left over goes last
  return { f: pool[day % pool.length], n: (day % pool.length) + 1, of: pool.length };
}
